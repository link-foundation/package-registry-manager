#!/usr/bin/env python3
"""Copy the plan-free tests of rust/tests/unit/publishers.rs into
tests/publishers_noplan.rs, since the harness does not build plan.rs."""
import pathlib
import re

here = pathlib.Path(__file__).resolve().parent
source = (here / "../../rust/tests/unit/publishers.rs").read_text()
parts = re.split(r"(?=\n#\[test\]\n)", source)
needs_plans = ("build_plans", "PlanOptions", "npm_plans")
tests = [part for part in parts[1:] if not any(name in part for name in needs_plans)]
head = re.sub(r"\nfn npm_plans.*?\n}\n", "\n", parts[0], flags=re.S)
head = re.sub(r"use package_registry_manager::\{[^}]*\};", "use package_registry_manager::*;", head, flags=re.S)
(here / "tests/publishers_noplan.rs").write_text(
    "// Generated by generate-publisher-tests.py; do not edit.\n"
    "#![allow(dead_code, unused_imports)]\n" + head + "".join(tests)
)
print(f"kept {len(tests)} of {len(parts) - 1} tests")
